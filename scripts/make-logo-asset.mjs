#!/usr/bin/env node
/**
 * Embeds public/brand/kognoz-logo.png as a TypeScript module so the Word
 * exporter can place the logo without reading public/ at runtime (Vercel
 * functions do not trace that folder). Re-run when the PNG changes:
 *   node scripts/make-logo-asset.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../public/brand/kognoz-logo.png", import.meta.url);
const out = new URL("../src/lib/export/assets/kognoz-logo.ts", import.meta.url);
const png = readFileSync(src);
if (png.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a") throw new Error("not a PNG");
const width = png.readUInt32BE(16);
const height = png.readUInt32BE(20);
const body = `/**
 * Generated by scripts/make-logo-asset.mjs from public/brand/kognoz-logo.png — do not edit.
 * ${width}×${height} PNG, ${png.length} bytes.
 */
export const KOGNOZ_LOGO = {
  type: "png" as const,
  width: ${width},
  height: ${height},
  base64:
    "${png.toString("base64")}",
} as const;
`;
writeFileSync(out, body);
console.log(`wrote ${out.pathname} (${width}×${height}, ${png.length} bytes)`);
